#1. Calcule a média ponderada de um aluno. Considere para isso três notas com pesos 3 (prova A), 5 (prova B) e 2 (trabalhos).

provaA = float(input('informe nota prova A'))
provaB = float(input('informe nota prova B'))
trabalhos = float(input('informe nota do trabalhos'))


mediaPonderada = (provaA * 0.3) + (provaB * 0.5) + (trabalhos * 0.2)

print('a media ponderada é:', mediaPonderada)





